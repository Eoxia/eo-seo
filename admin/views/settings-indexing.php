<?php
/**
 * View: settings, "Indexing" section.
 *
 * @package EoSeo
 *
 * @var array<string, mixed> $settings   Settings.
 * @var string               $option     Option name.
 * @var \WP_Post_Type[]      $post_types Post types.
 * @var \WP_Taxonomy[]       $taxonomies Taxonomies.
 */

defined( 'ABSPATH' ) || exit;

use EoSeo\Admin\Ui;
?>
<section class="eo-seo-card">
	<header class="eo-seo-card__head">
		<h2 class="eo-seo-card__title"><?php esc_html_e( 'Show to search engines', 'eo-seo' ); ?></h2>
		<p>
			<?php esc_html_e( 'Turned off, a type is set to noindex and left out of the sitemap.', 'eo-seo' ); ?>
			<?php if ( wp_sitemaps_get_server()->sitemaps_enabled() ) : ?>
				<a href="<?php echo esc_url( (string) get_sitemap_url( 'index' ) ); ?>" target="_blank" rel="noopener"><?php esc_html_e( 'See the sitemap', 'eo-seo' ); ?><span class="screen-reader-text"> <?php esc_html_e( '(opens in a new tab)', 'eo-seo' ); ?></span></a>
			<?php endif; ?>
		</p>
	</header>
	<div class="eo-seo-columns-2">
		<div>
			<h3 class="eo-seo-subtitle"><?php esc_html_e( 'Content types', 'eo-seo' ); ?></h3>
			<?php foreach ( $post_types as $eo_seo_name => $eo_seo_type ) : ?>
				<?php Ui::toggle( $option . '[index][post_types][' . $eo_seo_name . ']', ! empty( $settings['index']['post_types'][ $eo_seo_name ] ), $eo_seo_type->labels->name ); ?>
			<?php endforeach; ?>
		</div>
		<div>
			<h3 class="eo-seo-subtitle"><?php esc_html_e( 'Taxonomies', 'eo-seo' ); ?></h3>
			<?php foreach ( $taxonomies as $eo_seo_name => $eo_seo_taxonomy ) : ?>
				<?php Ui::toggle( $option . '[index][taxonomies][' . $eo_seo_name . ']', ! empty( $settings['index']['taxonomies'][ $eo_seo_name ] ), $eo_seo_taxonomy->labels->name ); ?>
			<?php endforeach; ?>
		</div>
	</div>
</section>

<section class="eo-seo-card">
	<header class="eo-seo-card__head">
		<h2 class="eo-seo-card__title"><?php esc_html_e( 'Pages without value for search engines', 'eo-seo' ); ?></h2>
	</header>
	<?php
	Ui::toggle( $option . '[noindex_search]', (bool) $settings['noindex_search'], __( 'Hide the internal search results', 'eo-seo' ), __( 'Recommended: these pages are endless and thin.', 'eo-seo' ) );
	Ui::toggle( $option . '[noindex_date]', (bool) $settings['noindex_date'], __( 'Hide the date archives', 'eo-seo' ), __( 'They repeat the contents of the categories.', 'eo-seo' ) );
	Ui::toggle( $option . '[author_archives]', (bool) $settings['author_archives'], __( 'Keep the author archives', 'eo-seo' ), __( 'Turned off, they redirect to the home page. Useful on a site with a single author.', 'eo-seo' ) );
	Ui::toggle( $option . '[attachment_pages]', (bool) get_option( 'wp_attachment_pages_enabled' ), __( 'Keep the attachment pages', 'eo-seo' ), __( 'Turned off (recommended), they redirect to the file.', 'eo-seo' ) );
	?>
</section>

<section class="eo-seo-card">
	<header class="eo-seo-card__head">
		<h2 class="eo-seo-card__title"><?php esc_html_e( 'Extra robots.txt rules', 'eo-seo' ); ?></h2>
		<p>
			<?php esc_html_e( 'Added to the robots.txt generated by WordPress, which already gives the address of the sitemap. No file is written on the server.', 'eo-seo' ); ?>
			<?php if ( EoSeo\Site_Audit::serves_robots_txt() ) : ?>
				<a href="<?php echo esc_url( home_url( '/robots.txt' ) ); ?>" target="_blank" rel="noopener"><?php esc_html_e( 'See robots.txt', 'eo-seo' ); ?><span class="screen-reader-text"> <?php esc_html_e( '(opens in a new tab)', 'eo-seo' ); ?></span></a>
			<?php else : ?>
				<strong><?php esc_html_e( 'WordPress is installed in a sub-folder: robots.txt is not generated, these rules do not apply.', 'eo-seo' ); ?></strong>
			<?php endif; ?>
		</p>
	</header>
	<label class="screen-reader-text" for="eo-seo-robots"><?php esc_html_e( 'Extra robots.txt rules', 'eo-seo' ); ?></label>
	<textarea id="eo-seo-robots" class="eo-seo-input eo-seo-input--code" rows="5" name="<?php echo esc_attr( $option ); ?>[robots_rules]" placeholder="Disallow: /private/"><?php echo esc_textarea( $settings['robots_rules'] ); ?></textarea>
</section>

<section class="eo-seo-card">
	<header class="eo-seo-card__head">
		<h2 class="eo-seo-card__title"><?php esc_html_e( 'Optimizations', 'eo-seo' ); ?></h2>
	</header>
	<?php
	Ui::toggle( $option . '[cleanup][extra_feeds]', ! empty( $settings['cleanup']['extra_feeds'] ), __( 'Remove the secondary feeds', 'eo-seo' ), __( 'Comments, categories, tags… links in the <head>.', 'eo-seo' ) );
	Ui::toggle( $option . '[cleanup][head_links]', ! empty( $settings['cleanup']['head_links'] ), __( 'Remove the useless links of the <head>', 'eo-seo' ), __( 'RSD, shortlink, generator, REST API, oEmbed.', 'eo-seo' ) );
	Ui::toggle( $option . '[cleanup][replytocom]', ! empty( $settings['cleanup']['replytocom'] ), __( 'Add nofollow to the "Reply" links of comments', 'eo-seo' ), __( 'Keeps the ?replytocom= addresses out of the index.', 'eo-seo' ) );
	Ui::toggle( $option . '[cleanup][comment_pages]', ! empty( $settings['cleanup']['comment_pages'] ), __( 'Hide the pages of comments', 'eo-seo' ), __( 'When comments are split into pages (Settings › Discussion), pages 2, 3… repeat the content: they are set to noindex.', 'eo-seo' ) );
	?>
</section>
