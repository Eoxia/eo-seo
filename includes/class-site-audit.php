<?php
/**
 * Site-wide SEO review (dashboard and eo-seo/audit-site).
 *
 * @package EoSeo
 */

namespace EoSeo;

defined( 'ABSPATH' ) || exit;

/**
 * Checks the settings, the indexing and the contents of the whole site. Local checks only: no HTTP request.
 */
final class Site_Audit {

	/**
	 * Runs the review.
	 *
	 * @return array<int, array{id: string, group: string, status: string, label: string, message: string, fix_url: string, view_url: string}>
	 *         Status: good, warning or error.
	 */
	public static function run(): array {
		$items = array();

		$public  = (bool) get_option( 'blog_public' );
		$items[] = self::item(
			'site_visible',
			'settings',
			$public ? 'good' : 'error',
			__( 'Visible to search engines', 'eo-seo' ),
			$public ? __( 'Search engines may index the site.', 'eo-seo' ) : __( 'The site asks search engines not to index it (Settings › Reading).', 'eo-seo' ),
			admin_url( 'options-reading.php' )
		);

		$structure = (string) get_option( 'permalink_structure' );
		$items[]   = self::item(
			'permalinks',
			'settings',
			'' !== $structure ? 'good' : 'error',
			__( 'Readable addresses', 'eo-seo' ),
			'' !== $structure ? __( 'Addresses use the post name.', 'eo-seo' ) : __( 'Addresses look like ?p=123: choose a permalink structure.', 'eo-seo' ),
			admin_url( 'options-permalink.php' )
		);

		$tagline = trim( (string) get_bloginfo( 'description' ) );
		$items[] = self::item(
			'tagline',
			'settings',
			'' !== $tagline ? 'good' : 'warning',
			__( 'Site title and tagline', 'eo-seo' ),
			'' !== $tagline ? __( 'The site has a tagline.', 'eo-seo' ) : __( 'The tagline is empty: it is used in the home page title.', 'eo-seo' ),
			admin_url( 'options-general.php' )
		);

		$https   = str_starts_with( home_url(), 'https://' );
		$items[] = self::item(
			'https',
			'settings',
			$https ? 'good' : 'error',
			__( 'HTTPS', 'eo-seo' ),
			$https ? __( 'The site address uses HTTPS.', 'eo-seo' ) : __( 'The site address does not use HTTPS.', 'eo-seo' ),
			admin_url( 'options-general.php' )
		);

		$items[] = self::item(
			'favicon',
			'settings',
			has_site_icon() ? 'good' : 'warning',
			__( 'Site icon', 'eo-seo' ),
			has_site_icon() ? __( 'The site has an icon (shown by Google next to the results).', 'eo-seo' ) : __( 'No site icon: Google shows a generic icon next to the results.', 'eo-seo' ),
			admin_url( 'options-general.php' )
		);

		$identity = (array) Settings::get( 'identity' );
		$has_logo = (int) $identity['logo'] || (int) get_theme_mod( 'custom_logo' );
		$items[]  = self::item(
			'identity',
			'settings',
			'' !== $identity['name'] && $has_logo ? 'good' : 'warning',
			__( 'Site identity', 'eo-seo' ),
			'' !== $identity['name'] && $has_logo ? __( 'Name and logo of the organization are set.', 'eo-seo' ) : __( 'Set the name and the logo of the organization or person behind the site.', 'eo-seo' ),
			Admin\Admin::page_url( 'eo-seo-settings', array( 'tab' => 'identity' ) )
		);

		$robots_file = file_exists( ABSPATH . 'robots.txt' );
		if ( ! self::serves_robots_txt() ) {
			// Search engines only read /robots.txt at the root of the domain: WordPress cannot generate it from a sub-folder.
			$items[] = self::item(
				'robots_txt',
				'indexing',
				'warning',
				'robots.txt',
				sprintf(
					/* translators: %s: folder of the site, e.g. /wordpress. */
					__( 'WordPress is installed in a sub-folder (%s): it does not generate robots.txt, which search engines only read at the root of the domain. EO SEO\'s rules do not apply.', 'eo-seo' ),
					Url::home_path()
				),
				''
			);
		} else {
			$items[] = self::item(
				'robots_txt',
				'indexing',
				$robots_file ? 'warning' : 'good',
				'robots.txt',
				$robots_file ? __( 'A physical robots.txt file exists at the root of the site: it replaces the one of WordPress and EO SEO\'s rules. Delete it or merge it by hand.', 'eo-seo' ) : __( 'robots.txt is generated by WordPress, with the address of the sitemap.', 'eo-seo' ),
				'',
				home_url( '/robots.txt' )
			);
		}

		// WordPress turns its sitemap off (404) while the site asks search engines not to index it.
		$sitemaps = wp_sitemaps_get_server()->sitemaps_enabled();
		if ( $sitemaps ) {
			$sitemap_message = __( 'The sitemap of WordPress is active.', 'eo-seo' );
			$sitemap_fix     = '';
		} elseif ( ! $public ) {
			$sitemap_message = __( 'Turned off by WordPress because the site asks search engines not to index it: allow indexing in Settings › Reading.', 'eo-seo' );
			$sitemap_fix     = admin_url( 'options-reading.php' );
		} else {
			$sitemap_message = __( 'Turned off by code: a theme or another plugin uses the wp_sitemaps_enabled filter.', 'eo-seo' );
			$sitemap_fix     = '';
		}
		$items[] = self::item( 'sitemap', 'indexing', $sitemaps ? 'good' : 'error', __( 'Sitemap', 'eo-seo' ), $sitemap_message, $sitemap_fix, $sitemaps ? (string) get_sitemap_url( 'index' ) : '' );

		$attachments = (bool) get_option( 'wp_attachment_pages_enabled' );
		$items[]     = self::item(
			'attachment_pages',
			'indexing',
			$attachments ? 'warning' : 'good',
			__( 'Attachment pages', 'eo-seo' ),
			$attachments ? __( 'Each media file has its own thin page: these pages should redirect to the file.', 'eo-seo' ) : __( 'Attachment pages redirect to the file.', 'eo-seo' ),
			Admin\Admin::page_url( 'eo-seo-settings', array( 'tab' => 'indexing' ) )
		);

		// Home page as search engines get it (checked on demand and every night).
		$home_check = Home_Check::last();
		$check_url  = wp_nonce_url( admin_url( 'admin-post.php?action=eo_seo_home_check' ), 'eo_seo_home_check' );
		if ( null === $home_check ) {
			$items[] = self::item( 'home_check', 'indexing', 'warning', __( 'Home page', 'eo-seo' ), __( 'Not checked yet: EO SEO loads the home page as a search engine and reads its title, description, canonical, H1 and the redirection from http to https.', 'eo-seo' ), '', '', $check_url, __( 'Check now', 'eo-seo' ) );
		} else {
			foreach ( $home_check['items'] as $result ) {
				$fix     = 'home_description' === $result['id'] ? Admin\Admin::page_url( 'eo-seo-settings' ) : '';
				$items[] = self::item( $result['id'], 'indexing', $result['status'], $result['label'], $result['message'], $fix );
			}
			$items[] = self::item(
				'home_check',
				'indexing',
				'good',
				__( 'Home page check', 'eo-seo' ),
				/* translators: %s: time since the check, e.g. "3 hours". */
				sprintf( __( 'Checked %s ago, again every night.', 'eo-seo' ), human_time_diff( (int) $home_check['time'] ) ),
				'',
				'',
				$check_url,
				__( 'Check again', 'eo-seo' )
			);
		}

		$extra_h1 = self::template_extra_h1();
		if ( null !== $extra_h1 ) {
			$items[] = self::item(
				'template_h1',
				'indexing',
				$extra_h1 ? 'warning' : 'good',
				__( 'H1 headings of the templates', 'eo-seo' ),
				$extra_h1
					/* translators: %s: list of headings (e.g. "site title"). */
					? sprintf( __( 'The templates print other H1 headings on every page (%s): only the page title should be an H1. Set them to another level in the site editor.', 'eo-seo' ), implode( ', ', $extra_h1 ) )
					: __( 'The templates print no other H1 than the page title.', 'eo-seo' ),
				admin_url( 'site-editor.php' )
			);
		}

		$conflicts = Compat::active_plugins();
		$items[]   = self::item(
			'seo_plugins',
			'indexing',
			$conflicts ? 'warning' : 'good',
			__( 'Other SEO plugins', 'eo-seo' ),
			$conflicts
				/* translators: %s: plugin names. */
				? sprintf( __( 'Also active: %s. EO SEO adds nothing on the front to avoid duplicates; keep only one SEO plugin.', 'eo-seo' ), implode( ', ', $conflicts ) )
				: __( 'EO SEO is the only SEO plugin.', 'eo-seo' ),
			admin_url( 'plugins.php' )
		);

		$levels  = Status::count_by_level();
		$items[] = self::item(
			'contents',
			'contents',
			$levels[ Checks::LEVEL_PROBLEM ] ? 'error' : ( $levels[ Checks::LEVEL_IMPROVE ] ? 'warning' : 'good' ),
			__( 'Contents', 'eo-seo' ),
			sprintf(
				/* translators: 1: number of contents with problems, 2: to improve, 3: good. */
				__( '%1$d with problems, %2$d to improve, %3$d good.', 'eo-seo' ),
				$levels[ Checks::LEVEL_PROBLEM ],
				$levels[ Checks::LEVEL_IMPROVE ],
				$levels[ Checks::LEVEL_GOOD ]
			),
			admin_url( 'edit.php?post_type=page&eo_seo_level=problem' )
		);

		$not_found = Not_Found_Log::count_new();
		$items[]   = self::item(
			'not_found',
			'contents',
			$not_found ? 'warning' : 'good',
			__( '404 errors', 'eo-seo' ),
			$not_found
				/* translators: %d: number of addresses. */
				? sprintf( _n( '%d missing address to redirect or handle.', '%d missing addresses to redirect or handle.', $not_found, 'eo-seo' ), $not_found )
				: __( 'No missing address to handle.', 'eo-seo' ),
			Admin\Admin::page_url( 'eo-seo-404' )
		);

		$without_alt = self::count_media_without_alt();
		$items[]     = self::item(
			'media_alt',
			'contents',
			$without_alt ? 'warning' : 'good',
			__( 'Alternative texts', 'eo-seo' ),
			$without_alt
				/* translators: %d: number of images. */
				? sprintf( _n( '%d image of the media library has no alternative text.', '%d images of the media library have no alternative text.', $without_alt, 'eo-seo' ), $without_alt )
				: __( 'Every image has an alternative text.', 'eo-seo' ),
			admin_url( 'upload.php?mode=list' )
		);

		$terms   = Status::count_terms_by_level();
		$worst   = $terms[ Checks::LEVEL_PROBLEM ] ? Checks::LEVEL_PROBLEM : ( $terms[ Checks::LEVEL_IMPROVE ] ? Checks::LEVEL_IMPROVE : '' );
		$message = sprintf(
			/* translators: 1: number of terms with problems, 2: to improve, 3: good. */
			__( '%1$d with problems, %2$d to improve, %3$d good.', 'eo-seo' ),
			$terms[ Checks::LEVEL_PROBLEM ],
			$terms[ Checks::LEVEL_IMPROVE ],
			$terms[ Checks::LEVEL_GOOD ]
		);
		if ( $terms['unknown'] ) {
			/* translators: %d: number of terms. */
			$message .= ' ' . sprintf( _n( '%d not analyzed yet: scan the site.', '%d not analyzed yet: scan the site.', $terms['unknown'], 'eo-seo' ), $terms['unknown'] );
		}
		$taxonomy = '' !== $worst ? self::first_taxonomy_with_level( $worst ) : '';
		$items[]  = self::item(
			'terms',
			'contents',
			Checks::LEVEL_PROBLEM === $worst ? 'error' : ( '' !== $worst ? 'warning' : 'good' ),
			__( 'Categories and tags', 'eo-seo' ),
			$message,
			'' !== $taxonomy ? add_query_arg(
				array(
					'taxonomy'     => $taxonomy,
					'eo_seo_level' => $worst,
				),
				admin_url( 'edit-tags.php' )
			) : ''
		);

		/**
		 * Filters the site review.
		 *
		 * @param array<int, array<string, string>> $items Items.
		 */
		return (array) apply_filters( 'eo_seo_site_audit', $items );
	}

	/**
	 * One item of the review.
	 *
	 * @param string $id      ID.
	 * @param string $group   settings, indexing or contents.
	 * @param string $status  good, warning or error.
	 * @param string $label   Label.
	 * @param string $message Message.
	 * @param string $fix_url  Where to fix it.
	 * @param string $view_url Where to see the result (sitemap, robots.txt…), empty when there is nothing to see.
	 * @return array{id: string, group: string, status: string, label: string, message: string, fix_url: string, view_url: string}
	 */
	private static function item( string $id, string $group, string $status, string $label, string $message, string $fix_url, string $view_url = '', string $action_url = '', string $action_label = '' ): array {
		return compact( 'id', 'group', 'status', 'label', 'message', 'fix_url', 'view_url', 'action_url', 'action_label' );
	}

	/**
	 * Whether WordPress serves /robots.txt: only when the site is at the root of the domain.
	 */
	public static function serves_robots_txt(): bool {
		return '' === Url::home_path();
	}

	/**
	 * H1 headings printed by the templates besides the page title (site title in the header…),
	 * read on the latest published page and post.
	 *
	 * @return string[]|null Headings, null when no template can be read (classic theme, no content).
	 */
	private static function template_extra_h1(): ?array {
		$known = false;
		$found = array();

		foreach ( array( 'page', 'post' ) as $post_type ) {
			$posts = get_posts(
				array(
					'post_type'      => $post_type,
					'post_status'    => 'publish',
					'posts_per_page' => 1,
				)
			);
			if ( ! $posts ) {
				continue;
			}
			$template = Template_Headings::for_post( $posts[0] );
			if ( $template['known'] ) {
				$known = true;
				$found = array_merge( $found, $template['other_h1'] );
			}
		}

		return $known ? array_values( array_unique( $found ) ) : null;
	}

	/**
	 * Images of the media library without alternative text.
	 */
	public static function count_media_without_alt(): int {
		global $wpdb;

		// phpcs:ignore WordPress.DB.DirectDatabaseQuery.DirectQuery, WordPress.DB.DirectDatabaseQuery.NoCaching -- Dashboard only.
		return (int) $wpdb->get_var(
			"SELECT COUNT(*) FROM {$wpdb->posts} p
			LEFT JOIN {$wpdb->postmeta} m ON m.post_id = p.ID AND m.meta_key = '_wp_attachment_image_alt'
			WHERE p.post_type = 'attachment' AND p.post_mime_type LIKE 'image/%' AND ( m.meta_value IS NULL OR m.meta_value = '' )"
		);
	}

	/**
	 * First handled taxonomy that has a term at a level (for the "Fix" link).
	 *
	 * @param string $level Level.
	 */
	private static function first_taxonomy_with_level( string $level ): string {
		global $wpdb;

		foreach ( array_keys( Settings::taxonomies() ) as $taxonomy ) {
			// phpcs:ignore WordPress.DB.DirectDatabaseQuery.DirectQuery, WordPress.DB.DirectDatabaseQuery.NoCaching -- Dashboard only.
			$found = $wpdb->get_var( $wpdb->prepare( "SELECT tt.term_id FROM {$wpdb->term_taxonomy} tt INNER JOIN {$wpdb->termmeta} m ON m.term_id = tt.term_id AND m.meta_key = %s AND m.meta_value = %s WHERE tt.taxonomy = %s LIMIT 1", Fields::STATUS_META, $level, $taxonomy ) );
			if ( $found ) {
				return $taxonomy;
			}
		}

		return '';
	}
}
